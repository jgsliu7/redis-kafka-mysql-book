def esc(s):return html.escape(str(s))
def wrap(s,width,size=13):
    lines=[]
    for part in s.split('\n'):
        line='';w=0
        for c in part:
            cw=size*(.56 if ord(c)<128 else 1)
            if w+cw>width and line:lines.append(line);line='';w=0
            line+=c;w+=cw
        lines.append(line)
    return lines
class SVG:
    def __init__(self,num,title,height):
        self.num=num;self.height=height;self.items=[];self.arrow_used=False
        title=TITLES.get(num,title)
        self.text(26,32,'图 '+num+'　'+title,18,'#1F2937',weight=650)
    def text(self,x,y,s,size=13,color='#374151',anchor='start',weight=400):
        self.items.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" text-anchor="{anchor}" font-weight="{weight}">{esc(s)}</text>')
    def rect(self,x,y,w,h,kind='n'):
        fg,bg=COLORS[kind];self.items.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{bg}" stroke="{fg}" stroke-width="1.3"/>')
    def line(self,x1,y1,x2,y2,arrow=False,color='#6B7280',dash=False):
        if arrow:self.arrow_used=True
        self.items.append(f'<path d="M{x1},{y1} L{x2},{y2}" fill="none" stroke="{color}" stroke-width="1.5"'+(' stroke-dasharray="5 4"' if dash else '')+(' marker-end="url(#arrow)"' if arrow else '')+'/>')
    def box(self,x,y,w,h,title,body='',kind='n'):
        self.rect(x,y,w,h,kind);fg,_=COLORS[kind]
        ty=y+25
        for l in wrap(title,w-28,14):self.text(x+14,ty,l,14,fg,weight=650);ty+=21
        ty+=7
        for l in (wrap(body,w-28,13) if body else []):self.text(x+14,ty,l);ty+=22
        if ty-22>y+h-10:raise ValueError(f'{self.num} 文本超出框：{title}')
    def note(self,y,s):
        for l in wrap(s,842,12):self.text(28,y,l,12,'#596273');y+=20
    def save(self):
        defs='<defs><marker id="arrow" markerWidth="10" markerHeight="10" refX="9" refY="5" orient="auto" markerUnits="userSpaceOnUse"><path d="M0,0 L10,5 L0,10 z" fill="#6B7280"/></marker></defs>' if self.arrow_used else ''
        out=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 900 {self.height}" role="img" aria-labelledby="title"><title id="title">图 {self.num} {esc(TITLES.get(self.num,getattr(self,"title","技术示意")))}</title><rect width="900" height="{self.height}" fill="white"/>'+defs+'<g font-family="system-ui,-apple-system,PingFang SC,Microsoft YaHei,sans-serif">'+''.join(self.items)+'</g></svg>'
        FILES[self.num].write_text(out,encoding='utf-8')
def grid(num,title,cols,note='',height=480):
    s=SVG(num,title,height);s.title=title;n=len(cols);w=(848-(n-1)*22)/n
    for i,(head,body,kind) in enumerate(cols):s.box(26+i*(w+22),66,w,height-146,head,body,kind)
    s.note(height-52,note);s.save()
def flow(num,title,steps,note='',kind='n'):
    s=SVG(num,title,120+len(steps)*92);s.title=title
    for i,item in enumerate(steps):
        head,body=item[:2];k=item[2] if len(item)>2 else kind;y=62+i*92
        s.box(128,y,644,72,head,body,k)
        if i<len(steps)-1:s.line(450,y+73,450,y+89,True)
    s.note(s.height-35,note);s.save()
def table(num,title,headers,rows,note='',widths=None):
    widths=widths or [848/len(headers)]*len(headers);rh=max(82,max(max(len(wrap(str(c),widths[j]-22,13)) for j,c in enumerate(row)) for row in rows)*22+26)
    s=SVG(num,title,132+rh*len(rows));s.title=title;x=26
    for w,h in zip(widths,headers):s.rect(x,60,w,40);s.text(x+11,86,h,14,weight=650);x+=w
    for i,row in enumerate(rows):
        x=26;y=100+i*rh
        for j,(w,c) in enumerate(zip(widths,row)):
            s.rect(x,y,w,rh,'r' if str(row[0]).startswith('Redis') else 'm' if str(row[0]).startswith(('MySQL','InnoDB')) else 'k' if str(row[0]).startswith('Kafka') else 'n')
            for z,l in enumerate(wrap(str(c),w-22,13)):s.text(x+11,y+25+z*22,l)
            x+=w
    s.note(s.height-15,note);s.save()

